<?php

declare(strict_types=1);

namespace EchoFusion\Contracts\DatabaseManager;

use Throwable;

/**
 * A database connection, small enough to be implemented on top of PDO, Doctrine DBAL
 * or any other library.
 *
 * Parameters are bound, never interpolated. They can be named (`:id`) or positional
 * (`?`); an array value bound to a named parameter expands to a list for `IN (:ids)`.
 */
interface ConnectionInterface
{
    /**
     * Run a query and return every row as an associative array.
     *
     * @param array<array-key, mixed> $params
     *
     * @return list<array<string, mixed>>
     */
    public function fetchAll(string $sql, array $params = []): array;

    /**
     * Run a query and return the first row, or null when there is none.
     *
     * @param array<array-key, mixed> $params
     *
     * @return array<string, mixed>|null
     */
    public function fetchOne(string $sql, array $params = []): ?array;

    /**
     * Run a query and return the first column of the first row, or null when there is none.
     *
     * @param array<array-key, mixed> $params
     */
    public function fetchValue(string $sql, array $params = []): mixed;

    /**
     * Run a statement that changes data and return the number of affected rows.
     *
     * @param array<array-key, mixed> $params
     */
    public function execute(string $sql, array $params = []): int;

    /**
     * The id generated by the last insert (a sequence name may be needed for some drivers).
     */
    public function lastInsertId(?string $name = null): string;

    /**
     * Run the callback in a transaction: commit when it returns, roll back and re-throw when it throws.
     * Nested calls must join the outer transaction safely.
     *
     * @template T
     *
     * @param callable(static): T $callback
     *
     * @return T
     *
     * @throws Throwable whatever the callback throws, after the rollback
     */
    public function transactional(callable $callback): mixed;

    public function beginTransaction(): void;

    public function commit(): void;

    public function rollBack(): void;

    public function inTransaction(): bool;
}
